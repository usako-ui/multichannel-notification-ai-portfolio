/**
 * 緊急パス判定用の正規表現
 * requirements.md 定義：クレーム|クレームです|苦情|至急|緊急対応|怒り
 *
 * ⚠️「緊急」単体は含めない。
 *    No.22「これは緊急ではありません」を通常パスに流すため（AC-007）。
 *    「緊急」を追加すると否定文まで拾ってしまう。
 *
 * ⚠️「クレーム」単体を追加した誤検知リスクを承知して採用（2026-09-15 変更）:
 *    - 追加理由：本番運用中に「クレームとして正式に申し入れます」という
 *      Gmail 本文が通常パスへ流れ、営業部長 LINE Push が発火しなかったため
 *    - トレードオフ：「これはクレームではありません」「クレーム対応マニュアル」
 *      のような文脈でも緊急発火してしまう可能性がある
 *    - 判断根拠：見逃し（SLA 5 分違反）のコストが誤検知（LINE Push 1 通誤送）
 *      のコストより大きい。誤検知は Gemini 分類側で最終的に正しいカテゴリに
 *      振り直される（handleUrgent は発火するが Slack #クレーム緊急 記録 +
 *      LINE Push 誤送だけで済み、業務停止には至らない）
 */
export const URGENT_PATTERN = /クレームです|クレーム|苦情|至急|緊急対応|怒り/;

/**
 * 本文に緊急キーワードが含まれるか判定する。
 * 迷ったら Gemini 分類でクレーム側に倒す設計のため、
 * ここでは正規表現の厳密一致のみ担当する。
 */
export function isUrgent(content: string): boolean {
  return URGENT_PATTERN.test(content);
}
