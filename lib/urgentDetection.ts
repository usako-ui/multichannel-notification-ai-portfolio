/**
 * 緊急パス判定ロジック（正規表現 + 否定形除外の二段階判定）
 *
 * 設計方針（2026-09-15 改訂）:
 *   1. URGENT_PATTERN で緊急キーワードを広めに拾う（見逃し防止・SLA 優先）
 *   2. NEGATION_PATTERN で「クレームではありません」等の否定形を除外
 *      → 誤検知（LINE Push 誤送）を防止しつつ、見逃し（SLA 5 分違反）は
 *        絶対に起こさない設計に倒す
 *
 * トレードオフ（既知の許容）:
 *   - 「以前クレームがあった件について」等の過去言及は緊急扱いになる
 *     → SLA 側に倒す方針（迷ったらクレーム扱い）で許容
 *   - 誤検知しても Gemini 分類で最終カテゴリは正しく振り直される
 *     （LINE Push 1 通誤送 + Slack #クレーム緊急 誤記録だけで済み、
 *       業務停止には至らない）
 */

/**
 * 緊急キーワード（広めに拾う）
 *
 * ⚠️「緊急」単体は含めない。
 *    No.22「これは緊急ではありません」を通常パスに流すため（AC-007）。
 *    「緊急」を追加すると否定形を含む文まで拾ってしまう
 *    （NEGATION_PATTERN は「緊急ではありません」を除外しない設計。
 *      「緊急」は単語として日常的に使われすぎるため、パターンから外す
 *      方が誤検知率が低い）。
 */
export const URGENT_PATTERN = /クレーム|苦情|至急|緊急対応|怒り/;

/**
 * 否定形の除外パターン
 *
 * 緊急キーワードの後 15 文字以内に否定表現が出現する場合、
 * 否定文とみなして緊急パスから除外する。
 *
 * 対応する否定形:
 *   - では(あり)?ま?せん  → ではありません / ではません / ではせん
 *   - じゃ(あり)?ま?せん  → じゃありません / じゃません / じゃせん
 *   - ではない            → ではない
 *   - じゃない            → じゃない
 *
 * 例（除外される）:
 *   - 「クレームではありません」
 *   - 「これは苦情じゃない」
 *   - 「至急ではない案件です」
 *
 * 例（除外されない = 緊急パス継続）:
 *   - 「クレームとして正式に申し入れます」
 *   - 「至急対応してください」
 *   - 「苦情を申し立てます」
 */
const NEGATION_PATTERN =
  /(?:クレーム|苦情|至急|怒り).{0,15}(?:では(?:あり)?ま?せん|じゃ(?:あり)?ま?せん|ではない|じゃない)/;

/**
 * 本文（件名＋本文の結合を推奨）に緊急キーワードが含まれ、
 * かつ否定形でない場合に true を返す。
 *
 * 呼び出し側（gmailPoller / LINE Webhook）は「件名 + 本文」を渡すこと。
 * Gmail の場合は「【件名】{subject}\n{body}」形式で結合する（gmailPoller.ts 参照）。
 */
export function isUrgent(content: string): boolean {
  if (!URGENT_PATTERN.test(content)) return false;
  if (NEGATION_PATTERN.test(content)) return false;
  return true;
}
